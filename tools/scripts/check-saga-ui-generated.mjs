import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const sourceRoot = fileURLToPath(new URL('../../', import.meta.url));
const generatedDirectories = [
    'src/ui/generated/workbench', 'src/loredecks/generated', 'assets/generated/loredeck-covers',
];

async function generatedFiles(root) {
    const files = [];
    async function visit(relative) {
        let entries;
        try { entries = await readdir(path.join(root, relative), { withFileTypes: true }); }
        catch (error) { if (error.code === 'ENOENT') return; throw error; }
        for (const entry of entries) {
            const child = `${relative}/${entry.name}`;
            if (entry.isDirectory()) await visit(child);
            else if (entry.isFile()) files.push(child);
            else throw new Error(`Unsupported generated artifact: ${child}`);
        }
    }
    for (const directory of generatedDirectories) await visit(directory);
    return files.sort();
}

/** Compare both complete sets and raw bytes, including checkout line endings. */
export async function compareGeneratedFiles(trackedRoot, rebuiltRoot) {
    const tracked = await generatedFiles(trackedRoot);
    const rebuilt = await generatedFiles(rebuiltRoot);
    const trackedSet = new Set(tracked);
    const rebuiltSet = new Set(rebuilt);
    const errors = [
        ...tracked.filter(file => !rebuiltSet.has(file)).map(file => `Stale extra artifact: ${file}`),
        ...rebuilt.filter(file => !trackedSet.has(file)).map(file => `Missing generated artifact: ${file}`),
    ];
    for (const file of rebuilt) {
        if (!trackedSet.has(file)) continue;
        const left = await readFile(path.join(trackedRoot, file));
        const right = await readFile(path.join(rebuiltRoot, file));
        if (!left.equals(right)) errors.push(`Generated bytes differ: ${file}`);
    }
    if (errors.length) throw new Error(errors.join('\n'));
    return rebuilt;
}

export async function checkGenerated() {
    const temporaryBase = path.resolve(tmpdir());
    const temporary = await mkdtemp(path.join(temporaryBase, 'saga-generated-'));
    try {
        const { build } = await import('vite');
        const { buildLoredeckThumbnails } = await import('./build-loredeck-thumbnails.mjs');
        await build({
            root: sourceRoot,
            configFile: path.join(sourceRoot, 'vite.saga-ui.config.mjs'),
            build: { outDir: path.join(temporary, 'src/ui/generated/workbench') },
        });
        await buildLoredeckThumbnails({ outputRoot: temporary });
        const files = await compareGeneratedFiles(sourceRoot, temporary);
        console.log(`Generated artifacts fresh: ${files.length} files, exact sets and bytes.`);
        return files;
    } finally {
        const resolved = path.resolve(temporary);
        if (path.dirname(resolved) !== temporaryBase || !path.basename(resolved).startsWith('saga-generated-')) {
            throw new Error(`Refusing temporary cleanup outside ${temporaryBase}`);
        }
        await rm(resolved, { recursive: true, force: true });
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    await checkGenerated();
}
