import { createHash } from 'node:crypto';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { getLoredeckAssetRef } from '../../src/loredecks/loredeck-cover-image.js';

const sourceRoot = fileURLToPath(new URL('../../', import.meta.url));
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export async function buildLoredeckThumbnails({ outputRoot = sourceRoot } = {}) {
    outputRoot = path.resolve(outputRoot);
    const index = JSON.parse(await readFile(path.join(sourceRoot, 'content/loredecks/index.json'), 'utf8'));
    const originals = [...new Set(index.bundled.map(record => getLoredeckAssetRef({
        ...record,
        manifest: `content/loredecks/${record.manifest}`,
    })?.path).filter(Boolean))].sort();
    const lookup = {};
    const originalMetadata = {};
    let originalBytes = 0;
    let derivativeBytes = 0;
    await mkdir(path.join(outputRoot, 'assets/generated/loredeck-covers'), { recursive: true });
    await mkdir(path.join(outputRoot, 'src/loredecks/generated'), { recursive: true });
    for (const original of originals) {
        if (!original.startsWith('content/loredecks/') || original.split('/').includes('..')) throw new Error(`Invalid bundled cover: ${original}`);
        const inputPath = path.join(sourceRoot, original);
        const input = await readFile(inputPath);
        const metadata = await sharp(input).metadata();
        originalBytes += (await stat(inputPath)).size;
        originalMetadata[original] = { width: metadata.autoOrient.width, height: metadata.autoOrient.height, bytes: input.length, sha256: sha256(input) };
        const identity = sha256(Buffer.from(original)).slice(0, 16);
        lookup[original] = [];
        for (const size of [128, 256]) {
            const { data, info } = await sharp(input).rotate()
                .resize({ width: size, height: size, fit: 'inside', withoutEnlargement: true })
                .webp({ lossless: true, effort: 6 }).toBuffer({ resolveWithObject: true });
            const relative = `assets/generated/loredeck-covers/${identity}-${size}.webp`;
            await writeFile(path.join(outputRoot, relative), data);
            lookup[original].push({ path: relative, width: info.width, height: info.height, bytes: data.length, sha256: sha256(data) });
            derivativeBytes += data.length;
        }
    }
    const header = '// Generated by tools/scripts/build-loredeck-thumbnails.mjs. Do not edit.\n';
    await writeFile(path.join(outputRoot, 'src/loredecks/generated/loredeck-cover-thumbnails.js'),
        `${header}export const BUNDLED_COVER_ORIGINALS = ${JSON.stringify(originalMetadata, null, 2)};\n\nexport const BUNDLED_COVER_THUMBNAILS = ${JSON.stringify(lookup, null, 2)};\n`);
    return { originals: originals.length, derivatives: originals.length * 2, originalBytes, derivativeBytes, encoding: 'lossless WebP', longEdges: [128, 256] };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    const index = process.argv.indexOf('--output-root');
    const inline = process.argv.find(arg => arg.startsWith('--output-root='));
    const outputRoot = inline?.slice('--output-root='.length) || (index >= 0 ? process.argv[index + 1] : sourceRoot);
    if (!outputRoot || outputRoot.startsWith('--')) throw new Error('--output-root requires a directory');
    console.log(JSON.stringify(await buildLoredeckThumbnails({ outputRoot }), null, 2));
}
